import { test, expect } from '@playwright/test'
const headers = { 'X-Admin-Request': '1', Origin: 'http://127.0.0.1:3111' }
test('real 404s and project-specific server metadata', async ({ request }) => {
  for (const path of ['/works/missing', '/works/%25invalid', '/assets/missing.js', '/uploads/missing.jpg', '/missing']) expect((await request.get(path)).status()).toBe(404)
  const html = await (await request.get('/works/mouse')).text()
  expect(html).toContain('<title>残障便利性鼠标 — Crtyss</title>')
  expect(html).toContain('property="og:image"')
  expect(await (await request.get('/admin')).text()).toContain('noindex, nofollow')
  expect((await request.delete('/api/admin/photos/forbidden', { headers })).status()).toBe(401)
})
test('API outage shows retry and never republishes seed content', async ({ page }) => {
  await page.route('**/api/content', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"offline"}' }))
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('作品暂时无法加载')
  await expect(page.locator('.project-card')).toHaveCount(0)
  await page.unroute('**/api/content')
  await page.getByRole('button', { name: '重新加载' }).click()
  await expect(page.locator('.project-card')).toHaveCount(10)
})
test('persistent home, project metadata, theme and history', async ({ page }) => {
  const warnings = []
  page.on('console', message => { if (message.text().includes('GSAP target')) warnings.push(message.text()) })
  await page.goto('/')
  await expect(page.locator('.project-card')).toHaveCount(10)
  await page.locator('.archive-grid .project-card').first().scrollIntoViewIfNeeded()
  await page.evaluate(() => { window.originalHome = document.querySelector('.home-page') })
  await page.locator('.archive-grid .project-card').first().evaluate(el => el.addEventListener('click', () => { window.homeY = scrollY }, { capture: true }))
  await page.locator('.archive-grid .project-card').first().click()
  await expect(page.locator('.route-page h1')).toBeVisible()
  await expect(page).not.toHaveTitle('Crtyss — 产品设计师')
  await page.locator('.detail-back').first().click()
  await expect(page.locator('.route-page')).toHaveCount(0)
  expect(await page.evaluate(() => document.querySelector('.home-page') === window.originalHome)).toBe(true)
  expect(await page.evaluate(() => Math.abs(scrollY - window.homeY))).toBeLessThan(4)
  await page.goBack()
  await expect(page.locator('.project-detail')).toBeVisible()
  await page.goBack()
  await expect(page.locator('.route-page')).toHaveCount(0)
  await page.locator('.theme-toggle').click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(warnings).toEqual([])
})
test('lazy admin and authenticated content changes across sessions', async ({ page, request }) => {
  const adminLoads = []
  page.on('request', req => { if (/\/Admin-[^/]+\.js/.test(req.url())) adminLoads.push(req.url()) })
  await page.goto('/')
  await expect(page.locator('.project-card')).toHaveCount(10)
  expect(adminLoads).toHaveLength(0)
  await page.goto('/admin')
  await page.getByLabel('管理员密码').fill('test-only-password-123')
  await page.getByRole('button', { name: '登录管理后台' }).click()
  await expect(page.getByRole('button', { name: '＋ 添加产品' })).toBeVisible()
  expect(adminLoads.length).toBeGreaterThan(0)
  const id = 'regression-' + Date.now()
  const result = await page.request.put(`/api/admin/photos/${id}`, { headers, data: { title: '测试摄影', category: 'nature', src: '/assets/photography/photo-01.jpg', width: 1168, height: 1752 } })
  expect(result.ok()).toBe(true)
  expect((await (await request.get('/api/content')).json()).photos.some(photo => photo.id === id)).toBe(true)
  expect((await page.request.delete(`/api/admin/photos/${id}`, { headers })).ok()).toBe(true)
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  expect((await page.request.delete(`/api/admin/photos/${id}`, { headers })).status()).toBe(401)
})
